#!/usr/bin/env python3
"""Generate Android string resources from the shared English/Czech catalog."""
import argparse
import hashlib
import json
from pathlib import Path
import re
from xml.sax.saxutils import escape
ROOT=Path(__file__).resolve().parents[1]

def outputs():
    catalog=json.loads((ROOT/'web/i18n/cs.json').read_text())
    pairs=sorted(catalog.items())
    for english,czech in pairs:
        if not czech or set(re.findall(r'\{\w+\}',english)) != set(re.findall(r'\{\w+\}',czech)):
            raise ValueError('Missing translation or mismatched placeholders: '+english)
    def rid(text): return 'ui_'+hashlib.sha1(text.encode()).hexdigest()[:12]
    def xml(text): return escape(text.replace('\\','\\\\').replace("'","\\'").replace('"','\\"').replace('\n','\\n'))
    files={}
    for folder,language in [('values',False),('values-cs',True)]:
        lines=['<?xml version="1.0" encoding="utf-8"?>','<!-- Generated by scripts/sync-translations.py; edit web/i18n/cs.json. -->','<resources>']
        lines += [f'    <string name="{rid(en)}" formatted="false">{xml(cs if language else en)}</string>' for en,cs in pairs]
        lines.append('</resources>')
        files[ROOT/f'android/app/src/main/res/{folder}/translations.xml']='\n'.join(lines)+'\n'
    entries='\n'.join(f'        IDS.put({json.dumps(en,ensure_ascii=False)},R.string.{rid(en)});' for en,_ in pairs)
    java='''package dev.rclimit;
// Generated by scripts/sync-translations.py; edit web/i18n/cs.json.
import android.content.Context;
import java.util.*;
import java.util.regex.*;
final class Translations {
    private static final Map<String,Integer> IDS=new LinkedHashMap<>();
    private static final List<Template> TEMPLATES=new ArrayList<>();
    private static class Template {
        final Pattern pattern;final List<String> names=new ArrayList<>();final int id;
        Template(String source,int resource) {
            id=resource;Matcher tokens=Pattern.compile("\\\\{(\\\\w+)\\\\}").matcher(source);
            StringBuilder regex=new StringBuilder("^");int pos=0;
            while(tokens.find()) {regex.append(Pattern.quote(source.substring(pos,tokens.start()))).append("(.*?)");names.add(tokens.group(1));pos=tokens.end();}
            regex.append(Pattern.quote(source.substring(pos))).append("$");pattern=Pattern.compile(regex.toString(),Pattern.DOTALL);
        }
    }
    static {
ENTRIES
        for(Map.Entry<String,Integer> item:IDS.entrySet()) if(item.getKey().contains("{")) TEMPLATES.add(new Template(item.getKey(),item.getValue()));
    }
    static String text(Context context,String source) {
        if(source==null) return "";
        Integer id=IDS.get(source);if(id!=null) return context.getString(id);
        for(Template item:TEMPLATES) {
            Matcher match=item.pattern.matcher(source);
            if(match.matches()) {String result=context.getString(item.id);for(int i=0;i<item.names.size();i++) result=result.replace("{"+item.names.get(i)+"}",match.group(i+1));return result;}
        }
        return source;
    }
}
'''.replace('ENTRIES',entries)
    files[ROOT/'android/app/src/main/java/dev/rclimit/Translations.java']=java
    return files

def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    for path,data in outputs().items():
        if args.check:
            if not path.is_file() or path.read_text()!=data: parser.exit(1,'Translations are stale. Run python3 scripts/sync-translations.py.\n')
        else:
            path.parent.mkdir(parents=True,exist_ok=True);path.write_text(data)
    print('Android/Czech translation resources '+('verified.' if args.check else 'generated.'))
if __name__=='__main__': main()
